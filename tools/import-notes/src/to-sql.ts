import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { songFields } from '@songbook/shared';
import { walk } from './fs';

/** Stable id from the file path, so re-seeding updates songs instead of duplicating them. */
export const songId = (rel: string) =>
  's_' + createHash('sha256').update(rel.replace(/\\/g, '/').replace(/\.cho$/, '')).digest('hex').slice(0, 16);

const q = (v: string | number | null) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);

export function toSql(files: { rel: string; chordpro: string }[], ts = Date.now()): string {
  const byNumber = new Map<number, string>();
  const out = ['-- Generated by tools/import-notes/src/to-sql.ts'];
  const upserts: string[] = [];
  for (const { rel, chordpro } of files) {
    const f = songFields(chordpro);
    if (f.number !== null) {
      const other = byNumber.get(f.number);
      if (other) throw new Error(`Duplicate number ${f.number}: ${other} and ${rel}`);
      byNumber.set(f.number, rel);
    }
    const id = songId(rel);
    // Free numbers that move first, so swapping numbers between songs never hits the unique index.
    out.push(`UPDATE songs SET number = NULL WHERE id = ${q(id)} AND number IS NOT ${q(f.number)};`);
    upserts.push(
      `INSERT INTO songs (id, number, title, key, bpm, time_sig, rhythm, chordpro, version, updated_at, deleted_at)
VALUES (${[id, f.number, f.title, f.key, f.bpm, f.timeSig, f.rhythm, chordpro].map(q).join(', ')}, 1, ${ts}, NULL)
ON CONFLICT(id) DO UPDATE SET number = excluded.number, title = excluded.title, key = excluded.key, bpm = excluded.bpm,
  time_sig = excluded.time_sig, rhythm = excluded.rhythm, chordpro = excluded.chordpro, version = songs.version + 1,
  updated_at = excluded.updated_at, deleted_at = NULL
WHERE songs.chordpro IS NOT excluded.chordpro OR songs.deleted_at IS NOT NULL OR songs.number IS NOT excluded.number;
INSERT OR IGNORE INTO song_versions (song_id, version, chordpro, created_at) SELECT id, version, chordpro, updated_at FROM songs WHERE id = ${q(id)};`,
    );
  }
  return [...out, ...upserts].join('\n') + '\n';
}

function main([dir, outFile]: string[]) {
  if (!dir || !outFile) {
    console.error('Usage: to-sql <choDir> <out.sql>');
    process.exit(1);
  }
  const files = walk(dir, ['.cho']).map((p) => ({ rel: relative(dir, p), chordpro: readFileSync(p, 'utf8') }));
  try {
    writeFileSync(outFile, toSql(files));
  } catch (e) {
    console.error(String(e instanceof Error ? e.message : e));
    process.exit(1);
  }
  console.log(`Wrote ${files.length} songs → ${outFile}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main(process.argv.slice(2));
