const DICTS: Record<Language, Record<string, string>> = { uk: {}, ru };

/** 1, 21 → one; 2–4, 22–24 → few; the rest → many (same rule in Ukrainian and Russian). */
const pluralForm = (n: number) => {
  const d = n % 10;
  const dd = n % 100;
  return d === 1 && dd !== 11 ? 0 : d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? 1 : 2;
};

export type Params = Record<string, string | number>;

export function translate(language: Language, key: string, params?: Params) {
  const text = DICTS[language]?.[key];
  if (__DEV__ && language !== 'uk' && text === undefined) console.warn(`i18n: no ${language} text for "${key}"`);
  let s = text ?? key;
  if (params?.count !== undefined && s.includes('|')) s = s.split('|')[pluralForm(Number(params.count))];
  return params ? s.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m)) : s;
}

let current: Language = 'uk';
/** Called by the settings store, so `t` outside components follows the chosen language. */
export const setLanguage = (language: Language) => {
  current = language;
};

/** For code outside components (alerts, error messages); reads the language at call time. */
export const t = (key: string, params?: Params) => translate(current, key, params);
